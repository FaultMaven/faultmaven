"""Runbook identifiers, and the containment check for the runbook directory.

Two related jobs: deterministic **id** derivation (the knowledge-item id of a
pre-deployed runbook, and the persisted runbook id ``runbook_id_from_parts``
mints, #1213), and the containment-checked **resolve** the standalone runbook
directory scan reads files through (``knowledge_root`` /
``resolve_runbook_path``).

No runbook is WRITTEN to disk. A draft's text lives in
``conversion_drafts.content`` and a published runbook's in
``knowledge_items.content`` (#1950); the directory is only an import source the
standalone scan reads.

Id derivation:

Shared single source of truth so the startup KB bootstrap
(``faultmaven.bootstrap.kb_init``) and the on-disk scan
(``faultmaven.modules.knowledge.domain.services.conversion_service.runbook_scan``)
agree on the id a given runbook file maps to. The scan uses it to recognize files the
bootstrap already published directly into ``knowledge_items`` (which never get
a ``conversion_drafts`` row), so it doesn't manufacture phantom drafts for
already-ingested runbooks.
"""

from __future__ import annotations

import hashlib
import re
from pathlib import Path
from uuid import uuid4

from faultmaven.utils.path_containment import PathEscape, resolve_within_root

# A bootstrap-published (platform built-in) runbook has a deterministic
# ``kb_<12-hex>`` item_id (see ``item_id_from_runbook_id``). This is the
# provenance discriminator the inventory surface uses to decide delete
# semantics: built-ins are *unpublished* (the file on disk would resurrect a
# hard delete on the next bootstrap), authored items are *hard-deleted*.
#
# The anchor is EXACTLY 12 hex chars on purpose: the manual-create path
# (``authored_item_id`` below) emits ``kb_<16-hex>``, so a
# loose prefix match would misclassify manually-authored items as built-ins.
_BUILTIN_ITEM_ID_RE = re.compile(r"^kb_[0-9a-f]{12}$")


def item_id_from_runbook_id(runbook_id: str | None) -> str:
    """Stable item_id derived from a runbook's frontmatter ``id``.

    Format: ``kb_{sha256(runbook_id)[:12]}``. Deterministic across runs;
    avoids collision with the random-uuid item_ids generated by the
    user-facing ``verify_draft`` path.

    ``None`` is accepted and treated as ``""``. Not defensive padding: a
    runbook file whose frontmatter carries a bare ``id:`` parses to ``None``,
    and the disk scan calls this on exactly that value — so the previous
    ``AttributeError`` aborted the whole walk on the class of malformed legacy
    file the scan exists to surface. ``None`` and ``""`` are both "no id" and
    map to the same degenerate item_id, which no caller should treat as real.
    """
    digest = hashlib.sha256((runbook_id or "").encode("utf-8")).hexdigest()[:12]
    return f"kb_{digest}"


def is_builtin_item_id(item_id: str) -> bool:
    """True if ``item_id`` is a bootstrap-published platform built-in.

    Built-ins match ``^kb_[0-9a-f]{12}$`` exactly. Authored items
    (verify_draft / API create) use random UUIDs or ``kb_<16-hex>`` and do
    not match. Used by the inventory delete path to pick unpublish (built-in)
    vs hard-delete (authored).
    """
    return bool(item_id and _BUILTIN_ITEM_ID_RE.match(item_id))


def authored_item_id() -> str:
    """item_id for a USER-authored runbook (verify_draft / API create).

    ``kb_<16-hex>`` — 16 hex chars so it NEVER matches the 12-hex built-in
    discriminator (``_BUILTIN_ITEM_ID_RE`` / ``is_builtin_item_id``). Authored
    items must be hard-deletable on request and MUST NOT be swept by the
    bootstrap orphan-prune, which deletes only ids matching the built-in
    pattern. A 12-hex authored id would be silently prune-deleted on the next
    redeploy with a changed pack — this helper is the single mint point that
    keeps authored ids out of that pattern.
    """
    return f"kb_{uuid4().hex[:16]}"


# Everything outside the allowlist collapses to a single hyphen. This is an
# ALLOWLIST on purpose (#1213): a denylist here would have to anticipate
# ``../``, ``..\``, ``....//``, absolute paths, NUL and control bytes, and
# whatever the filesystem normalises next. An allowlist has to anticipate
# nothing — a character either survives or it does not.
_SLUG_RE = re.compile(r"[^a-z0-9]+")

#: Bound for a **persisted runbook id** (``runbook_id_from_parts``): a value
#: already written into ``conversion_drafts.runbook_id`` and into runbook
#: frontmatter, so changing it re-mints ids that already exist in the database.
_MAX_RUNBOOK_ID_CHARS = 60
#: An over-long id keeps up to 55 characters of readable slug plus ``-`` plus a
#: 4-hex disambiguator, landing on ``_MAX_RUNBOOK_ID_CHARS`` (or one shorter,
#: when the truncation point lands on a hyphen — see ``runbook_id_from_parts``).
_RUNBOOK_ID_HASH_CHARS = 4

#: Stem for the id of a ``(service, title)`` pair with no allowlisted
#: characters at all. Followed by ``-`` and ``_EMPTY_SLUG_HASH_CHARS`` hex of
#: the RAW pair, so two such pairs get DIFFERENT ids while the same pair keeps
#: getting the same one.
_EMPTY_SLUG_STEM = "runbook"
_EMPTY_SLUG_HASH_CHARS = 8

#: Recognises an id minted by that branch. Used by callers that want a more
#: informative fallback than a bare hash (``mint_case_runbook_id`` prefers
#: the case's own stem when the draft's title carried nothing readable).
_HASH_ONLY_ID_RE = re.compile(
    rf"^{_EMPTY_SLUG_STEM}-[0-9a-f]{{{_EMPTY_SLUG_HASH_CHARS}}}$"
)


def _slug(value: str | None) -> str:
    """Lowercase, allowlist-filtered, hyphen-collapsed. May return ``""``."""
    return _SLUG_RE.sub("-", (value or "").lower()).strip("-")


def runbook_id_from_parts(service: str | None, title: str | None) -> str:
    """The PERSISTED runbook id for a ``(service, title)`` pair.

    Single mint point for the two call sites that write this value to the
    database and into runbook frontmatter — ``generate_runbook_id`` (the LLM
    conversion path) and ``ConversionService.create_runbook_from_template``
    (the manual path). Both previously carried their own byte-identical copy of
    this expression; the copies are what #1213's review recorded as "the slug
    rule now exists in three places".

    Two policies sit over the ``_slug`` character rule:

    - **Over-length.** An id keeps 55 slug characters plus an md5 disambiguator
      so two long titles that share a 60-character prefix still get distinct
      ids.
    - **Empty result.** An id with no allowlisted characters gets a
      hash-derived stem (see below).

    **Invariant: the result always matches ``^[a-z0-9]+(-[a-z0-9]+)*$``** — the
    grammar ``RunbookValidator`` enforces on frontmatter ``id``, non-empty by
    construction. Two branches used to break it (#1230, #1243):

    - A ``(service, title)`` pair with no allowlisted characters — punctuation
      only, or a non-latin script — returned ``""``. Two such runbooks
      persisted two ``conversion_drafts`` rows with ``runbook_id = ''`` and one
      identical ``item_id_from_runbook_id('')``, which no unique constraint
      rejected. They now get ``runbook-<8 hex of the pair, unambiguously
      encoded>``: non-empty,
      kebab, deterministic (re-converting a source must arrive at the id its
      live draft holds, so the same pair must keep minting the same value), and
      — **among
      pairs that reach this branch** — different for different pairs. That
      scoping is deliberate and load-bearing; see the boundary paragraph below,
      because the branch fires only when the WHOLE pair filters to nothing.
    - Truncation could land on a hyphen, so ``slug[:55] + "-" + md5`` emitted a
      **double** hyphen — 5 of the 91 shipped runbook titles, measured with
      their real frontmatter ``service``. The kept prefix is now ``rstrip``ed
      of hyphens before the disambiguator is joined on. The hash is still taken
      over the FULL slug, so two long titles sharing a 55-character prefix stay
      distinct.

    A third change is not about validity at all, and is called out separately
    because it DOES alter an id that was valid:

    - **A ``None`` part is normalised to ``""``** (see the comment on ``raw``).
      Stringified, it became the literal ``"none"``, which is not empty — so
      the hash branch could not see it and three punctuation-only titles under
      a ``None`` service all minted ``"none"``. ``"none-title"`` becomes
      ``"title"``.

    **Nothing REACHABLE that was already valid changed.** The first two
    branches fire only on input whose old id the validator already rejected
    (empty is a missing required field *and* a grammar failure; a double hyphen
    is a grammar failure), so no *usable* persisted id is re-minted. The third
    fires only on ``None``, which no call site can pass — all four supply a
    ``str``. That is the property that made this change affordable, and
    ``tests/unit/utils/test_runbook_id_consolidation.py`` pins it as a
    differential against the pre-consolidation originals rather than as a
    comment, with the ``None`` exemption named and bounded to exactly the
    inputs that carry one.

    What this does NOT do is make the id globally unique. Two distinct titles
    that slug identically still mint the same id, and they must — determinism
    is what refuses a second draft of one source, and a pure
    function cannot see the other rows. Two shapes reach that, and the second
    is worth naming because it looks like it should have been covered:

    - ``("svc", "Foo Bar")`` and ``("svc", "foo-bar")`` — the same slug.
    - ``("redis", "!!!")`` and ``("redis", "???")`` — **both mint ``"redis"``**.
      The hash branch does not fire, because it keys on the pair filtering to
      *nothing*, and here the service survives. Extending it to "the title
      contributed nothing" would re-mint ``("redis", "")``-shaped ids that are
      valid today, which is the one thing this change is not allowed to do.

    (Two long titles cut to the same 55 characters are NOT in that list — the
    md5 is taken over the FULL slug, so it separates those. It is 4 hex
    characters, i.e. 65536 values, so two distinct long slugs can still land on
    one id; that is a residual of the length bound, not a shape of the slug
    rule, and the guards below catch it the same way because they key on this
    function's OUTPUT rather than on its inputs.)

    Uniqueness is therefore not this function's job; it is enforced twice
    downstream, once for each place another draft can be:

    - **Against committed rows** — the partial unique index on
      ``(organization_id, runbook_id)`` from migration 046, checked ahead of
      the write by ``ConversionService.refuse_if_draft_slot_taken`` and
      surfaced as a 409 by ``_raise_if_runbook_id_taken``.
    - **Against the rest of its own job** — ``_partition_failure_modes``
      (#1258). Nothing is committed while a multi-failure-mode conversion runs,
      so the index and the re-read above are both blind to two drafts in ONE
      job minting one id; that pair used to write both runbooks to a single
      file and then fail the commit with a bare ``IntegrityError``. It is now
      refused before either conversion runs.

    The md5 is a disambiguator, not a secret: its input is the slug (or, on the
    empty branch, the pair the caller supplied), neither of which the id hides.
    """
    # ``or ""`` rather than letting the f-string stringify: ``None`` used to
    # become the literal ``"none"``, so ``(None, "!!!")``, ``(None, "???")`` and
    # ``(None, "。。。")`` all minted ``"none"`` — the #1230 collision, reintroduced
    # through the one input the signature admits and the hash branch cannot
    # see (the slug is not empty, it is ``"none"``). It also put a ``none-``
    # prefix on every ordinary title. No call site passes ``None`` today — all
    # four supply a ``str`` — so no persisted id can have been minted this way;
    # the signature is the promise being repaired.
    service, title = service or "", title or ""
    slug = _slug(f"{service}-{title}")
    if not slug:
        # Hashed over an UNAMBIGUOUS encoding of the pair, not over the joined
        # string. Joining makes the delimiter part of the data: ``("!", "@-#")``
        # and ``("!-@", "#")`` both join to ``"!-@-#"`` and minted one id — and
        # one ``item_id_from_runbook_id`` — which is exactly the #1230 collision
        # this branch exists to remove. ``repr`` of the tuple quotes and escapes
        # both parts, so distinct inputs cannot share an encoding.
        digest = hashlib.md5(
            repr((service, title)).encode("utf-8"), usedforsecurity=False
        ).hexdigest()[:_EMPTY_SLUG_HASH_CHARS]
        return f"{_EMPTY_SLUG_STEM}-{digest}"
    if len(slug) > _MAX_RUNBOOK_ID_CHARS:
        suffix = hashlib.md5(slug.encode(), usedforsecurity=False).hexdigest()[
            :_RUNBOOK_ID_HASH_CHARS
        ]
        keep = _MAX_RUNBOOK_ID_CHARS - _RUNBOOK_ID_HASH_CHARS - 1
        # ``rstrip`` BEFORE joining: ``_slug`` never emits a run of hyphens, so
        # the only way a double hyphen reaches the output is the cut landing on
        # one. The prefix cannot strip to empty — ``_slug`` also never emits a
        # LEADING hyphen.
        slug = slug[:keep].rstrip("-") + "-" + suffix
    return slug


def is_hash_only_runbook_id(runbook_id: str | None) -> bool:
    """True if ``runbook_id`` carries no readable text — only the hash stem.

    ``runbook_id_from_parts`` emits ``runbook-<8 hex>`` when the
    ``(service, title)`` pair filters to nothing (#1230). The id is valid and
    unique, but it says nothing about what the runbook is, so a caller holding
    a better name can prefer that instead. ``mint_case_runbook_id`` does:
    it falls back to the case's own stem, which is opaque but at least
    traceable to the incident.

    It is a *signal*, not a guard — an id that is not hash-only is not thereby
    guaranteed readable, and a real title of ``"Runbook 3fa2b1c0"`` on an empty
    service would match. Nothing security-relevant hangs on either direction.
    """
    return bool(runbook_id and _HASH_ONLY_ID_RE.match(runbook_id))


