_CHAIN_RUNBOOK = """## Causes

### Cause A: Disk full
**Statement:** The data volume reached 100% utilization.
**Chain:**
- root: A runaway process writes unbounded logs
- s1: Free space drops below the write threshold
- D: Writes fail and the service errors
**Indicators:**
- root: [Step 1] log volume grows without rotation
**Interventions:**
- **remediation** (root): Add log rotation. **Verification:** volume stabilizes.
"""


def test_single_linear_chain_nodes_edges_and_types():
    (cause,) = extract_causes(_CHAIN_RUNBOOK)
    assert cause["cause_letter"] == "A"
    assert cause["cause_name"] == "Disk full"
    assert cause["is_fallback_cause"] is False
    assert [n["node_type"] for n in cause["chain_nodes"]] == [
        "root",
        "intermediate",
        "problem",
    ]
    assert cause["chain_edges"] == [
        {"cause_ref": "root", "effect_ref": "s1"},
        {"cause_ref": "s1", "effect_ref": "D"},
    ]


def test_html_comments_stripped_from_chain_and_indicators():
    content = """## Causes

### Cause A: X
**Statement:** S
**Chain:**
- root: real statement <!-- match: some-directive -->
- D: the problem
**Indicators:**
- root: [Symptom] observable <!-- annotation -->
**Interventions:**
- **remediation** (root): fix
"""
    (cause,) = extract_causes(content)
    root = cause["chain_nodes"][0]
    assert root["statement"] == "real statement"
    assert cause["rung_indicators"]["root"] == ["[Symptom] observable"]


def test_converges_directive_is_an_edge_not_a_node():
    content = """## Causes

### Cause A: X
**Statement:** S
**Chain:**
- root: the root
- converges: B.s1
**Indicators:**
- root: [Symptom] x
**Interventions:**
- **remediation** (root): fix
"""
    (cause,) = extract_causes(content)
    # converges does not add a node ...
    assert [n["ref"] for n in cause["chain_nodes"]] == ["root"]
    # ... it records a convergence edge from the prior rung onto B.s1.
    assert cause["chain_edges"] == [
        {"cause_ref": "root", "effect_ref": "B.s1", "converges": True}
    ]


# ---------------------------------------------------------------------------
# Best-effort / adversarial — malformed pieces skipped, never raised
