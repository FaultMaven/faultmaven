"""Tests for the in-repo v4 cause extractor (``runbook_cause_extractor``).

The extractor is the produce-side counterpart of the KB pack builder's
``_extract_causes``: it turns a case→runbook conversion's v4 markdown into the
``metadata["causes"]`` record the Phase-4 seeder consumes, so a resolved case
re-enters diagnosis as structured candidates.

The load-bearing test is the **golden cross-check**: the extractor's output must
byte-match the record the upstream kb-toolkit builder computes for the same
markdown (produce/consume symmetry). The two repos cannot import one another, so
the expected record is vendored (``fixtures/runbook_cause_extractor/``) — it was
generated by running ``kb_toolkit.core.pack_builder._extract_causes`` on the
vendored fixture; regenerate both together if the shared grammar changes.
"""

import json
from pathlib import Path

import pytest

from faultmaven.modules.knowledge.domain.services.runbook_cause_extractor import (
    extract_causes,
)

pytestmark = pytest.mark.unit

_FIXTURES = Path(__file__).parent / "fixtures" / "runbook_cause_extractor"


def _load_golden() -> tuple[str, list]:
    content = (_FIXTURES / "golden_runbook.md").read_text(encoding="utf-8")
    expected = json.loads(
        (_FIXTURES / "golden_expected.json").read_text(encoding="utf-8")
    )
    return content, expected


# ---------------------------------------------------------------------------
# Golden cross-check — produce/consume symmetry with kb-toolkit
# ---------------------------------------------------------------------------


def test_golden_cross_check_matches_kb_toolkit_builder():
    """Extractor output is byte-identical to the kb-toolkit pack builder's for a
    fixture exercising every grammar branch: a multi-rung chain, a ``converges``
    edge, a multi-indicator rung, quadrant-tagged interventions, and the fallback
    Cause (``[Default]``, empty chain)."""
    content, expected = _load_golden()
    assert extract_causes(content) == expected


def test_golden_covers_every_record_field():
    """Guard the fixture itself stays representative: the expected record must
    exercise chain_nodes/edges, a converges edge, multi-value rung_indicators,
    interventions, and a fallback cause — else the golden silently narrows."""
    _, expected = _load_golden()
    assert any(c["chain_nodes"] and c["chain_edges"] for c in expected)
    assert any(e.get("converges") for c in expected for e in c["chain_edges"])
    assert any(
        len(vals) > 1 for c in expected for vals in c["rung_indicators"].values()
    )
    assert any(c["interventions"] for c in expected)
    assert any(c["is_fallback_cause"] for c in expected)


