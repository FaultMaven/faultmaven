def test_no_causes_section_returns_empty():
    assert extract_causes("# Title\n\n## Overview\nno causes here\n") == []


def test_empty_string_returns_empty():
    assert extract_causes("") == []


def test_cause_heading_outside_causes_section_is_ignored():
    # A ``### Cause``-style heading in another section must not be parsed.
    content = """## Diagnostic Steps
### Cause A: not a real cause heading

## Causes

### Cause A: real cause
**Statement:** S
**Interventions:**
- **remediation** (root): fix
"""
    causes = extract_causes(content)
    assert len(causes) == 1
    assert causes[0]["cause_statement"] == "S"


def test_chainless_cause_yields_empty_chain_not_error():
    # RULE-4 makes **Chain** optional for a simple one-step cause. The extractor
    # emits an empty chain (the seeder synthesizes root→D from the Statement).
    content = """## Causes

### Cause A: Simple one-step cause
**Statement:** The config flag was set to the wrong value.
**Indicators:**
- root: [Symptom] feature behaves incorrectly
**Interventions:**
- **remediation** (root): correct the flag. **Verification:** behavior restored.
"""
    (cause,) = extract_causes(content)
    assert cause["chain_nodes"] == []
    assert cause["chain_edges"] == []
    assert cause["cause_statement"] == "The config flag was set to the wrong value."
    assert cause["is_fallback_cause"] is False


def test_malformed_intervention_and_missing_fields_do_not_raise():
    # Garbage interventions / missing sub-fields are skipped, not raised.
    content = """## Causes

### Cause A: Sparse cause
**Statement:** only a statement, nothing else structured
**Interventions:**
- not a tagged intervention bullet
- **remediation** malformed no parens
"""
    (cause,) = extract_causes(content)
    assert cause["cause_statement"] == "only a statement, nothing else structured"
    assert cause["chain_nodes"] == []
    assert cause["interventions"] == []  # neither bullet is a valid quadrant mark
