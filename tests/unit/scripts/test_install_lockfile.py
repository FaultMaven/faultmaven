"""CI and the image install a lockfile the same way: torch's CPU build.

``scripts/install-lockfile.sh`` installs the torch the lockfile pins from the
PyTorch CPU index, then the rest of the lockfile without the lines only torch's
CUDA build needs. The image always did this, but CI installed the lockfiles as
written: 3.1 GB of nvidia-*/cuda-*/triton wheels per job, and a different torch
from the one that ships.

The script runs here against a stand-in ``python`` that records every pip
call and reads its "installed" distributions from a directory the test fills,
so nothing is downloaded or installed.
"""

from __future__ import annotations

import re
import stat
import subprocess
import sys
from pathlib import Path

import pytest

pytestmark = pytest.mark.unit

REPO_ROOT = Path(__file__).resolve().parents[3]
SCRIPT = REPO_ROOT / "scripts" / "install-lockfile.sh"
CPU_INDEX = "https://download.pytorch.org/whl/cpu"

LOCKFILE = """\
# This file was autogenerated by uv via the following command:
cuda-bindings==13.2.0
    # via torch
fastapi==0.121.0
    # via faultmaven (pyproject.toml)
nvidia-cublas==13.1.1.3
    # via cuda-toolkit
sentence-transformers==6.1.0
    # via faultmaven (pyproject.toml)
sympy==1.14.0
    # via torch
torch==2.13.0
    # via
    #   faultmaven (pyproject.toml)
    #   sentence-transformers
triton==3.7.1
    # via torch
"""

# A stand-in for `python`: `-m pip ...` is recorded (an `install -r FILE` also
# keeps a copy of FILE, which the script deletes on exit), and `-` runs the
# script's own installed-packages check with the real interpreter, seeing only
# the distributions in $FAKE_SITE.
FAKE_PYTHON = """\
#!/bin/sh
if [ "$1" = "-m" ]; then
    echo "$*" >> "$PIP_LOG"
    if [ "$3" = "install" ] && [ "$4" = "-r" ]; then
        cp "$5" "$CAPTURED"
        echo "$5" > "$CAPTURED.path"
    fi
    # FAIL_ON names a step by its subcommand and first option.
    if [ -n "$FAIL_ON" ]; then
        case "$3 $4" in "$FAIL_ON"*) exit 1 ;; esac
    fi
    exit 0
fi
if [ "$1" = "-" ]; then
    PYTHONPATH="$FAKE_SITE" exec "$REAL_PYTHON" -S -
fi
echo "unexpected python call: $*" >&2
exit 2
"""


def _dist(site: Path, name: str, version: str) -> None:
    info = site / f"{name.replace('-', '_')}-{version}.dist-info"
    info.mkdir(parents=True)
    (info / "METADATA").write_text(
        f"Metadata-Version: 2.1\nName: {name}\nVersion: {version}\n"
    )


def _run(
    tmp_path: Path,
    lockfile: str = LOCKFILE,
    installed: tuple[tuple[str, str], ...] = (("torch", "2.13.0+cpu"),),
    fail_on: str = "",
) -> tuple[subprocess.CompletedProcess, list[str]]:
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    fake = bin_dir / "python"
    fake.write_text(FAKE_PYTHON)
    fake.chmod(fake.stat().st_mode | stat.S_IXUSR)
    site = tmp_path / "site"
    site.mkdir()
    for name, version in installed:
        _dist(site, name, version)
    req = tmp_path / "requirements.txt"
    req.write_text(lockfile)
    log = tmp_path / "pip.log"
    log.touch()

    proc = subprocess.run(
        ["sh", str(SCRIPT), str(req)],
        env={
            "PATH": f"{bin_dir}:/usr/bin:/bin",
            "PIP_LOG": str(log),
            "CAPTURED": str(tmp_path / "captured.txt"),
            "FAKE_SITE": str(site),
            "REAL_PYTHON": sys.executable,
            "FAIL_ON": fail_on,
            "TMPDIR": str(tmp_path),
        },
        capture_output=True,
        text=True,
    )
    return proc, log.read_text().splitlines()


def test_torch_comes_from_the_cpu_index_at_the_locked_version_then_the_rest(
    tmp_path,
):
    proc, calls = _run(tmp_path)

    assert proc.returncode == 0, proc.stderr
    assert calls[0] == (
        f"-m pip install --no-deps --index-url {CPU_INDEX} torch==2.13.0"
    )
    assert re.fullmatch(r"-m pip install -r \S+", calls[1]), calls
    assert calls[2:] == ["-m pip check"]
    assert "torch 2.13.0+cpu, no GPU packages" in proc.stdout


def test_the_rest_is_the_lockfile_without_torch_and_its_gpu_stack(tmp_path):
    proc, _ = _run(tmp_path)

    assert proc.returncode == 0, proc.stderr
    pins = [
        line
        for line in (tmp_path / "captured.txt").read_text().splitlines()
        if line and not line.startswith(" ") and not line.startswith("#")
    ]
    assert pins == ["fastapi==0.121.0", "sentence-transformers==6.1.0", "sympy==1.14.0"]


def test_the_filtered_copy_is_removed(tmp_path):
    proc, _ = _run(tmp_path)

    assert proc.returncode == 0, proc.stderr
    written = Path((tmp_path / "captured.txt.path").read_text().strip())
    assert written.parent == tmp_path, "mktemp did not honour TMPDIR"
    assert not written.exists()


def test_a_lockfile_that_pins_no_torch_is_refused_before_any_install(tmp_path):
    proc, calls = _run(tmp_path, lockfile="fastapi==0.121.0\n")

    assert proc.returncode != 0
    assert "pins no torch" in proc.stderr
    assert calls == []


def test_a_gpu_package_that_got_installed_fails_the_install(tmp_path):
    proc, _ = _run(
        tmp_path,
        installed=(
            ("torch", "2.13.0"),
            ("nvidia-cublas", "13.1.1.3"),
            ("triton", "3.7.1"),
        ),
    )

    assert proc.returncode != 0
    assert "GPU packages were installed: nvidia-cublas, triton" in proc.stderr


@pytest.mark.parametrize("step", ["install --no-deps", "install -r", "check"])
def test_a_failing_pip_step_fails_the_install(tmp_path, step):
    proc, calls = _run(tmp_path, fail_on=step)

    assert proc.returncode != 0
    assert step in calls[-1], "the script ran on past the failed step"


def test_ci_and_the_image_install_lockfiles_only_through_the_script():
    """A job copied from one written before the script would install the CUDA
    build again. Nothing would fail; every job would just be 3 GB slower."""
    plain = re.compile(r"pip install\b[^\n]*-r\s+\S*requirements/\w+\.txt")
    offenders = [
        f"{path.relative_to(REPO_ROOT)}:{n}: {line.strip()}"
        for path in sorted((REPO_ROOT / ".github" / "workflows").glob("*.y*ml"))
        for n, line in enumerate(path.read_text().splitlines(), 1)
        # A --dry-run only resolves the lockfile as written; it installs nothing.
        if plain.search(line) and "--dry-run" not in line
    ]
    assert offenders == []

    dockerfile = (REPO_ROOT / "Dockerfile").read_text()
    assert "scripts/install-lockfile.sh" in dockerfile
    assert not re.search(r"pip install[^\n]*-r ", dockerfile)


def test_the_local_sync_strips_and_installs_the_same_way():
    """``scripts/sync-venv.sh`` does with uv what the script does with pip.
    The two copies of the rule must agree, or a local venv is not CI's."""

    def value(path: Path, name: str) -> str:
        match = re.search(rf"^{name}=['\"]([^'\"]+)['\"]$", path.read_text(), re.M)
        assert match, f"{name}= is not in {path.name}"
        return match.group(1)

    sync = REPO_ROOT / "scripts" / "sync-venv.sh"
    assert value(sync, "GPU_ONLY") == value(SCRIPT, "gpu_only")
    assert value(sync, "CPU_INDEX") == value(SCRIPT, "cpu_index")
